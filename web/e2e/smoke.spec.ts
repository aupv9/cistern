import { expect, test } from '@playwright/test'

test('overview loads with jobs, alerts and approvals', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Overview', level: 1 })).toBeVisible()
  await expect(page.getByText('shop-db failed its last 2 backups.')).toBeVisible()
  const jobs = page.getByRole('region', { name: 'Jobs' })
  await expect(jobs.getByRole('link', { name: 'orders-db' })).toBeVisible()
  await expect(jobs.getByRole('img', { name: /Last 30 runs/ }).first()).toBeVisible()
  await expect(page.getByRole('link', { name: /^Approvals\s*, 1 pending$/ })).toBeVisible()
})

test('status filter narrows the jobs table', async ({ page }) => {
  await page.goto('/')
  const jobs = page.getByRole('region', { name: 'Jobs' })
  await expect(jobs.getByRole('link', { name: 'orders-db' })).toBeVisible()
  await jobs.getByRole('button', { name: /Verify overdue/ }).click()
  await expect(jobs.getByRole('link', { name: 'users-db' })).toBeVisible()
  await expect(jobs.getByRole('link', { name: 'orders-db' })).toHaveCount(0)
  await jobs.getByRole('button', { name: /^All/ }).click()
  await jobs.getByRole('searchbox', { name: 'Search jobs' }).fill('ship')
  await expect(jobs.getByText('No jobs match these filters.')).toBeVisible()
})

test('a restore into production waits for approval', async ({ page }) => {
  await page.goto('/jobs/orders-db')
  await page.getByRole('link', { name: 'Restore', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Restore orders-db' })).toBeVisible()
  await page.getByRole('radio', { name: /production/ }).check()
  await expect(page.getByText('--set host=pg-orders.internal')).toBeVisible()
  await page.getByLabel('Reason').fill('INC-4821: order rows deleted by a faulty migration')
  const submit = page.getByRole('button', { name: 'Request approval' })
  await expect(submit).toBeDisabled()
  await page.getByLabel(/to confirm/).fill('orders-db')
  await expect(submit).toBeEnabled()
  await submit.click()
  await expect(page.getByText(/is waiting for approval/)).toBeVisible()
  await page.getByRole('link', { name: 'Open the request' }).click()
  await expect(page.getByText(/You asked for this restore/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Approve and start restore' })).toBeDisabled()
})

test('the theme toggle switches to dark and is remembered', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('/')
  const html = page.locator('html')
  const bg = () => page.evaluate(() => getComputedStyle(document.body).backgroundColor)
  await expect.poll(bg).toBe('rgb(250, 250, 250)')
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await expect(html).toHaveAttribute('data-theme', 'dark')
  await expect.poll(bg).toBe('rgb(0, 0, 0)')
  await page.reload()
  await expect(html).toHaveAttribute('data-theme', 'dark')
  await expect(page.getByRole('button', { name: 'Switch to light theme' })).toBeVisible()
})
