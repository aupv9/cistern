import { expect, test } from '@playwright/test'

test('the job page shows drill evidence and a drill runs from the UI', async ({ page }) => {
  await page.goto('/jobs/orders-db')
  const card = page.getByRole('region', { name: /^Restore drill/ })
  await expect(card.getByTestId('drill-evidence')).toHaveText(/^Restored and checked \d+ days? ago: 14 tables, 1\.\d M rows, all checks passed\.$/)
  await expect(card.getByRole('table', { name: /Drill checks/ })).toBeVisible()
  await expect(card.getByRole('table', { name: /Largest restored tables/ })).toBeVisible()
  await card.getByRole('button', { name: 'Run drill now' }).click()
  await page.waitForURL(/\/runs\/run_/)
  await expect(page.getByRole('heading', { name: 'Restore drill orders-db', level: 1 })).toBeVisible()
  await expect(page.getByText('Restore drill of orders-db succeeded.')).toBeAttached({ timeout: 20_000 })
  const result = page.getByRole('region', { name: /Drill result/ })
  await expect(result.getByTestId('drill-evidence')).toHaveText(/^Restored and checked just now: 14 tables/)
})

test('the history charts answer to the keyboard', async ({ page }) => {
  await page.goto('/jobs/orders-db')
  const history = page.getByRole('region', { name: /^History/ })
  const chart = history.getByRole('group', { name: 'Backup duration' })
  await chart.focus()
  await page.keyboard.press('Home')
  await expect(history.locator('.chart-tip').first()).toContainText('Aug')
  await history.getByRole('button', { name: 'Table' }).click()
  await expect(history.getByRole('table', { name: /Backups of orders-db/ })).toBeVisible()
})

test('an operator previews a prune and sees locked snapshots', async ({ page }) => {
  await page.goto('/jobs/billing-db')
  await page.getByRole('link', { name: 'Preview prune' }).click()
  await expect(page.getByRole('heading', { name: 'Prune billing-db', level: 1 })).toBeVisible()
  await page.getByRole('button', { name: 'Preview prune' }).click()
  await expect(page.getByLabel('Prune totals')).toBeVisible()
  await expect(page.getByTestId('locked-warning')).toContainText('still under Object Lock')
  await expect(page.getByText('Running a prune needs the Admin role.')).toBeVisible()
})

test('an admin runs a prune after typing the job name', async ({ page }) => {
  await page.addInitScript(() => window.localStorage.setItem('cistern.mock.roles', 'viewer,operator,admin'))
  await page.goto('/jobs/uploads/prune')
  const run = page.getByRole('button', { name: 'Run prune' })
  await expect(run).toBeDisabled()
  await page.getByRole('button', { name: 'Preview prune' }).click()
  await expect(page.getByText(/A prune would remove \d+ snapshots/)).toBeVisible()
  await page.getByLabel('Reason').fill('CHG-112: free space after the retention change')
  await page.getByLabel(/to confirm/).fill('uploads')
  await expect(run).toBeEnabled()
  await run.click()
  await page.waitForURL(/\/runs\/run_/)
  await expect(page.getByRole('heading', { name: 'Prune uploads', level: 1 })).toBeVisible()
  const result = page.getByRole('region', { name: 'Prune result' })
  await expect(result).toBeVisible({ timeout: 20_000 })
  await expect(result.getByLabel('Prune counts')).toContainText('Removed')
})

test('the configuration view redacts secrets and links the literal one', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: 'Configuration' }).click()
  await expect(page.getByRole('heading', { name: 'Configuration', level: 1 })).toBeVisible()
  await expect(page.getByText('A secret is written into the file.')).toBeVisible()
  await page.getByRole('link', { name: /^line \d+$/ }).click()
  await expect(page).toHaveURL(/#L\d+$/)
  const line = page.locator('.cfg-line.secret')
  await expect(line).toBeFocused()
  await expect(line.locator('.redacted')).toHaveText('<redacted>')
})
